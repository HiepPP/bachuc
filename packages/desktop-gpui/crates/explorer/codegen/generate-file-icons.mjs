#!/usr/bin/env node
// Writes `src/file_icon_data.rs`: the file icon SVGs and the extension table of the Electron
// explorer, with the colors toned down as `file-icon-svg.ts` does.
// Usage: node generate-file-icons.mjs
// Reads packages/app/src/components/material-file-icons.ts (the vendor table), file-icon-svg.ts
// (for ICON_CHROMA), and utils/color.ts (for desaturateHexColor). Output is deterministic, so a
// second run changes nothing. Node 22.18 or later strips the TypeScript types on import.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const crateDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(crateDir, "..", "..", "..", "..");
const components = join(repoRoot, "packages", "app", "src", "components");
const { desaturateHexColor } = await import(
  join(repoRoot, "packages", "app", "src", "utils", "color.ts")
);

const table = readFileSync(join(components, "material-file-icons.ts"), "utf8");
const toning = readFileSync(join(components, "file-icon-svg.ts"), "utf8");
const chroma = Number(/const ICON_CHROMA = ([\d.]+);/.exec(toning)?.[1]);
if (!Number.isFinite(chroma)) throw new Error("ICON_CHROMA not found in file-icon-svg.ts");

const icons = new Map();
for (const match of table.matchAll(/^ {2}(_default|[A-Za-z_]+): `(<svg[^`]*<\/svg>)`,$/gm)) {
  icons.set(
    match[1],
    match[2].replace(/#[0-9a-fA-F]+/g, (hex) => desaturateHexColor(hex, chroma)),
  );
}
const extensions = new Map();
const extensionBlock = /const EXTENSION_TO_ICON[^{]*\{([^}]*)\}/.exec(table)?.[1] ?? "";
for (const match of extensionBlock.matchAll(/^\s*([a-z0-9_]+): "([a-z0-9_]+)",$/gm)) {
  if (!icons.has(match[2])) throw new Error(`extension ${match[1]} names a missing icon`);
  extensions.set(match[1], match[2]);
}
if (!icons.has("_default") || icons.size < 50 || extensions.size < 50) {
  throw new Error(`parsed ${icons.size} icons and ${extensions.size} extensions`);
}

const byKey = ([a], [b]) => {
  if (a < b) return -1;
  return a > b ? 1 : 0;
};
let out = `// Generated by codegen/generate-file-icons.mjs from packages/app/src/components/material-file-icons.ts.
// Do not edit; run the generator again when the app's icon table changes.

/// The icon SVGs by name, sorted by name.
pub(crate) static ICONS: &[(&str, &str)] = &[
`;
for (const [name, svg] of [...icons].sort(byKey)) out += `    ("${name}", r###"${svg}"###),\n`;
out += `];

/// The icon name per lower case file extension, sorted by extension.
pub(crate) static EXTENSIONS: &[(&str, &str)] = &[
`;
for (const [extension, name] of [...extensions].sort(byKey)) {
  out += `    ("${extension}", "${name}"),\n`;
}
out += "];\n";
writeFileSync(join(crateDir, "src", "file_icon_data.rs"), out);
console.log(`wrote ${icons.size} icons and ${extensions.size} extensions`);
