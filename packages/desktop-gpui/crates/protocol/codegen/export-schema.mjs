// Exports the WebSocket envelope schemas of the built @getpaseo/protocol package as JSON Schema,
// for the Rust types that build.rs generates. Run `npm run build:client` first.
// Usage: node packages/desktop-gpui/crates/protocol/codegen/export-schema.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { WSInboundMessageSchema, WSOutboundMessageSchema } from "@getpaseo/protocol/messages";
import { z } from "zod";

const OUTPUT = fileURLToPath(new URL("./protocol.schema.json", import.meta.url));
const REPO_ROOT = fileURLToPath(new URL("../../../../../", import.meta.url));

// Zod types that JSON Schema cannot hold. With `unrepresentable: "any"` they export as `{}`,
// so the Rust side reads them as untyped JSON.
const UNREPRESENTABLE = new Set([
  "bigint",
  "custom",
  "date",
  "function",
  "map",
  "nan",
  "promise",
  "set",
  "symbol",
  "transform",
  "undefined",
  "void",
]);

function exportSchema(name, schema, anyFallbacks) {
  return z.toJSONSchema(schema, {
    target: "draft-07",
    io: "input",
    unrepresentable: "any",
    override: ({ zodSchema, path }) => {
      const type = zodSchema._zod.def.type;
      if (UNREPRESENTABLE.has(type)) {
        anyFallbacks.push({ root: name, path: path.join("/"), zodType: type });
      }
    },
  });
}

const anyFallbacks = [];
const roots = {
  WsInbound: exportSchema("WsInbound", WSInboundMessageSchema, anyFallbacks),
  WsOutbound: exportSchema("WsOutbound", WSOutboundMessageSchema, anyFallbacks),
};

const document = {
  $comment: "Generated by export-schema.mjs from @getpaseo/protocol. Do not edit by hand.",
  anyFallbacks,
  roots,
};
writeFileSync(OUTPUT, `${JSON.stringify(document, null, 2)}\n`);
// The pre-commit hook checks staged JSON, so write the file as the formatter leaves it.
execFileSync("npm", ["run", "--silent", "format:files", "--", OUTPUT], {
  cwd: REPO_ROOT,
  stdio: "ignore",
});
console.log(`wrote ${OUTPUT}`);
console.log(`${anyFallbacks.length} schemas fell back to any`);
for (const fallback of anyFallbacks) {
  console.log(`  ${fallback.root} ${fallback.zodType} at /${fallback.path}`);
}
